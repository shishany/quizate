import type { Difficulty } from '@quizate/game';

/**
 * Sample question bank for the web demo. General knowledge only, written for the demo, with the correct answer
 * first (options are shuffled per match). Religious content is left out on purpose: it needs the content and
 * Sharia review of BRD section 6. Local sample data only; never production content (CLAUDE.md).
 */
export type Category = 'geography' | 'science' | 'history' | 'sports' | 'general' | 'saudi';

export interface BiText {
  ar: string;
  en: string;
}

export interface SeedQuestion {
  id: string;
  category: Category;
  difficulty: Difficulty;
  text: BiText;
  /** Correct answer first. */
  options: [BiText, BiText, BiText, BiText];
  campaignId?: string;
}

type Opt = [string, string];
let n = 0;
function q(
  category: Category,
  difficulty: Difficulty,
  ar: string,
  en: string,
  correct: Opt,
  ...wrong: Opt[]
): SeedQuestion {
  n += 1;
  const opts = [correct, ...wrong].map(([a, e]) => ({ ar: a, en: e }));
  return {
    id: `q-${String(n).padStart(3, '0')}`,
    category,
    difficulty,
    text: { ar, en },
    options: opts as SeedQuestion['options'],
  };
}

